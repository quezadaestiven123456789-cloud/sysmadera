    private OrderDetail buildDetail(Furniture furniture, int quantity, BigDecimal unitPrice, Order order) {
        var d = OrderDetail.builder()
                .quantity(quantity).unitPrice(unitPrice)
                .subtotal(unitPrice.multiply(BigDecimal.valueOf(quantity)))
                .furniture(furniture)
                .build();
        d.setOrder(order);
        return d;
    }

