    @Nested
    @DisplayName("Furniture")
    class FurnitureAudit {

        @Test
        @DisplayName("createdAt should be auto-generated on persist")
        void createdAt_shouldBeAutoGenerated() {
            var entity = Furniture.builder()
                    .name("Mesa Roble").price(new BigDecimal("350.00")).stockQuantity(10)
                    .build();

            var saved = furnitureRepository.saveAndFlush(entity);

            assertThat(saved.getCreatedAt()).isNotNull();
        }

        @Test
        @DisplayName("updatedAt should be set on initial persist")
        void updatedAt_shouldBeSet_onCreate() {
            var entity = Furniture.builder()
                    .name("Silla Pino").price(new BigDecimal("85.00")).stockQuantity(25)
                    .build();

            var saved = furnitureRepository.saveAndFlush(entity);

            assertThat(saved.getUpdatedAt()).isNotNull();
        }

        @Test
        @DisplayName("createdAt should remain unchanged after update")
        void createdAt_shouldRemainUnchanged_afterUpdate() throws Exception {
            var saved = furnitureRepository.saveAndFlush(Furniture.builder()
                    .name("Estante").price(new BigDecimal("200.00")).stockQuantity(5)
                    .build());
            entityManager.clear();
            var originalCreatedAt = furnitureRepository.findById(saved.getId()).orElseThrow().getCreatedAt();

            Thread.sleep(10);
            var toUpdate = furnitureRepository.findById(saved.getId()).orElseThrow();
            toUpdate.setName("Estante Premium");
            furnitureRepository.saveAndFlush(toUpdate);
            entityManager.clear();

            var reloaded = furnitureRepository.findById(saved.getId()).orElseThrow();
            assertThat(reloaded.getCreatedAt()).isEqualTo(originalCreatedAt);
        }

        @Test
        @DisplayName("updatedAt should change after update")
        void updatedAt_shouldChange_afterUpdate() throws Exception {
            var saved = furnitureRepository.saveAndFlush(Furniture.builder()
                    .name("Cómoda").price(new BigDecimal("800.00")).stockQuantity(3)
                    .build());
            entityManager.clear();
            var originalUpdatedAt = furnitureRepository.findById(saved.getId()).orElseThrow().getUpdatedAt();

            Thread.sleep(10);
            var toUpdate = furnitureRepository.findById(saved.getId()).orElseThrow();
            toUpdate.setPrice(new BigDecimal("900.00"));
            furnitureRepository.saveAndFlush(toUpdate);
            entityManager.clear();

            var reloaded = furnitureRepository.findById(saved.getId()).orElseThrow();
            assertThat(reloaded.getUpdatedAt()).isAfter(originalUpdatedAt);
        }
    }

